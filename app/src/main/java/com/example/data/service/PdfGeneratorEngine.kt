package com.example.data.service

import android.content.Context
import android.content.Intent
import android.graphics.Bitmap
import android.graphics.Canvas
import android.graphics.Color
import android.graphics.Paint
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import android.net.Uri
import androidx.core.content.FileProvider
import java.io.File
import java.io.FileOutputStream
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

object PdfGeneratorEngine {

    const val PAGE_WIDTH = 595 // A4 standard width (pt)
    const val PAGE_HEIGHT = 842 // A4 standard height (pt)

    /**
     * Generates a beautifully formatted PDF document from AI output or user text.
     */
    fun createDocumentPdf(
        context: Context,
        title: String,
        author: String = "Bidiok Super AI",
        content: String
    ): File {
        val pdfDocument = PdfDocument()
        val paint = Paint().apply { isAntiAlias = true }

        val marginLeft = 40f
        val marginRight = 40f
        val contentWidth = PAGE_WIDTH - marginLeft - marginRight
        val marginTop = 50f
        val marginBottom = 50f

        val titlePaint = Paint().apply {
            color = Color.rgb(10, 25, 47)
            textSize = 20f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
            isAntiAlias = true
        }

        val metaPaint = Paint().apply {
            color = Color.rgb(80, 90, 110)
            textSize = 10f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
            isAntiAlias = true
        }

        val bodyPaint = Paint().apply {
            color = Color.rgb(25, 30, 40)
            textSize = 12f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
            isAntiAlias = true
        }

        val lineSpacing = 18f
        val dateStr = SimpleDateFormat("MMM dd, yyyy HH:mm", Locale.getDefault()).format(Date())

        // Break text into lines that fit within contentWidth
        val paragraphs = content.split("\n")
        val lines = mutableListOf<String>()

        for (paragraph in paragraphs) {
            if (paragraph.isBlank()) {
                lines.add("")
                continue
            }
            val words = paragraph.split(" ")
            var currentLine = StringBuilder()
            for (word in words) {
                val candidate = if (currentLine.isEmpty()) word else "$currentLine $word"
                if (bodyPaint.measureText(candidate) <= contentWidth) {
                    currentLine = StringBuilder(candidate)
                } else {
                    lines.add(currentLine.toString())
                    currentLine = StringBuilder(word)
                }
            }
            if (currentLine.isNotEmpty()) {
                lines.add(currentLine.toString())
            }
        }

        var lineIndex = 0
        var pageNumber = 1

        while (lineIndex < lines.size || pageNumber == 1) {
            val pageInfo = PdfDocument.PageInfo.Builder(PAGE_WIDTH, PAGE_HEIGHT, pageNumber).create()
            val page = pdfDocument.startPage(pageInfo)
            val canvas: Canvas = page.canvas

            // Page Background
            canvas.drawColor(Color.rgb(252, 253, 255))

            var currentY = marginTop

            // Header only on first page or running header
            if (pageNumber == 1) {
                // Header Banner Accent
                val headerRectPaint = Paint().apply { color = Color.rgb(0, 180, 216) }
                canvas.drawRect(marginLeft, currentY, marginLeft + 6f, currentY + 36f, headerRectPaint)

                // Title
                canvas.drawText(title.take(45), marginLeft + 14f, currentY + 18f, titlePaint)
                canvas.drawText("Generated by $author • $dateStr", marginLeft + 14f, currentY + 34f, metaPaint)

                currentY += 50f

                // Accent divider
                val dividerPaint = Paint().apply {
                    color = Color.rgb(220, 226, 235)
                    strokeWidth = 1.2f
                }
                canvas.drawLine(marginLeft, currentY, PAGE_WIDTH - marginRight, currentY, dividerPaint)
                currentY += 24f
            } else {
                canvas.drawText("$title — Page $pageNumber", marginLeft, currentY, metaPaint)
                currentY += 20f
                val dividerPaint = Paint().apply {
                    color = Color.rgb(230, 235, 245)
                    strokeWidth = 1f
                }
                canvas.drawLine(marginLeft, currentY, PAGE_WIDTH - marginRight, currentY, dividerPaint)
                currentY += 24f
            }

            // Draw body lines until page boundary
            while (lineIndex < lines.size && currentY + lineSpacing <= (PAGE_HEIGHT - marginBottom)) {
                val line = lines[lineIndex]
                if (line.isNotEmpty()) {
                    canvas.drawText(line, marginLeft, currentY, bodyPaint)
                }
                currentY += lineSpacing
                lineIndex++
            }

            // Footer
            val footerPaint = Paint().apply {
                color = Color.rgb(150, 160, 175)
                textSize = 9f
                isAntiAlias = true
            }
            canvas.drawText("Bidiok AI Quantum Enterprise Document Engine • Page $pageNumber", marginLeft, PAGE_HEIGHT - 25f, footerPaint)

            pdfDocument.finishPage(page)
            pageNumber++

            if (lineIndex >= lines.size) break
        }

        val cacheDir = context.cacheDir
        val safeTitle = title.replace(Regex("[^a-zA-Z0-9_-]"), "_").take(30)
        val file = File(cacheDir, "Bidiok_${safeTitle}_${System.currentTimeMillis()}.pdf")
        val outputStream = FileOutputStream(file)
        pdfDocument.writeTo(outputStream)
        pdfDocument.close()
        outputStream.close()

        return file
    }

    /**
     * Converts a Bitmap image into a single-page PDF.
     */
    fun createImagePdf(context: Context, bitmap: Bitmap, title: String): File {
        val pdfDocument = PdfDocument()
        val pageInfo = PdfDocument.PageInfo.Builder(PAGE_WIDTH, PAGE_HEIGHT, 1).create()
        val page = pdfDocument.startPage(pageInfo)
        val canvas = page.canvas

        canvas.drawColor(Color.WHITE)

        val titlePaint = Paint().apply {
            color = Color.BLACK
            textSize = 16f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
            isAntiAlias = true
        }
        canvas.drawText(title, 40f, 50f, titlePaint)

        // Scale bitmap to fit
        val maxWidth = (PAGE_WIDTH - 80).toFloat()
        val maxHeight = (PAGE_HEIGHT - 120).toFloat()
        val scale = minOf(maxWidth / bitmap.width, maxHeight / bitmap.height)
        val targetW = bitmap.width * scale
        val targetH = bitmap.height * scale
        val left = (PAGE_WIDTH - targetW) / 2f
        val top = 80f

        val scaledBitmap = Bitmap.createScaledBitmap(bitmap, targetW.toInt(), targetH.toInt(), true)
        canvas.drawBitmap(scaledBitmap, left, top, null)

        pdfDocument.finishPage(page)

        val file = File(context.cacheDir, "Bidiok_Image_${System.currentTimeMillis()}.pdf")
        val outputStream = FileOutputStream(file)
        pdfDocument.writeTo(outputStream)
        pdfDocument.close()
        outputStream.close()

        return file
    }

    /**
     * Share PDF intent
     */
    fun sharePdf(context: Context, pdfFile: File) {
        try {
            val authority = "${context.packageName}.fileprovider"
            val uri: Uri = FileProvider.getUriForFile(context, authority, pdfFile)
            val shareIntent = Intent(Intent.ACTION_SEND).apply {
                type = "application/pdf"
                putExtra(Intent.EXTRA_STREAM, uri)
                putExtra(Intent.EXTRA_SUBJECT, pdfFile.name)
                addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
                addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            }
            context.startActivity(Intent.createChooser(shareIntent, "Share Bidiok AI PDF").apply {
                addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            })
        } catch (e: Exception) {
            e.printStackTrace()
            // Direct file intent fallback
            val shareIntent = Intent(Intent.ACTION_SEND).apply {
                type = "application/pdf"
                putExtra(Intent.EXTRA_SUBJECT, pdfFile.name)
                addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            }
            context.startActivity(Intent.createChooser(shareIntent, "Share PDF").apply {
                addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            })
        }
    }
}
